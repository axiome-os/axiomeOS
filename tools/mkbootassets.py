#!/usr/bin/env python3
"""Generate include/bootsplash_assets.h from resources/.

The bootloader and the kernel are both freestanding and cannot depend on an
image decoder at runtime.  This script turns the logo source asset into a
plain 8-bit coverage mask:

  * resources/axiome.svg -> filled logo mask (anti-aliased raster)

The output deliberately has no external Python dependencies: the SVG path
uses only M/L/H/V/Z commands, so asset regeneration works in a bare
`nix develop` shell.
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
RES = ROOT / "resources"
OUT = ROOT / "include" / "bootsplash_assets.h"

LOGO_W = 240

# Tiny SVG path rasteriser
def _svg_path_polygons(d: str) -> list[list[tuple[float, float]]]:
    tokens = re.findall(r"[MmLlHhVvZz]|[-+]?(?:\d*\.\d+|\d+\.?)(?:[eE][-+]?\d+)?", d)
    polys: list[list[tuple[float, float]]] = []
    poly: list[tuple[float, float]] = []
    x = y = 0.0
    start = (0.0, 0.0)
    cmd = ""
    i = 0

    def num() -> float:
        nonlocal i
        v = float(tokens[i])
        i += 1
        return v

    while i < len(tokens):
        if tokens[i].isalpha():
            cmd = tokens[i]
            i += 1
            if cmd in ("Z", "z"):
                if poly:
                    polys.append(poly)
                poly = []
                x, y = start
                continue
        if cmd in ("M", "m"):
            nx, ny = num(), num()
            if cmd == "m":
                nx += x
                ny += y
            if poly:
                polys.append(poly)
            x, y = nx, ny
            start = (x, y)
            poly = [(x, y)]
            cmd = "L" if cmd == "M" else "l"
        elif cmd in ("L", "l"):
            nx, ny = num(), num()
            if cmd == "l":
                nx += x
                ny += y
            x, y = nx, ny
            poly.append((x, y))
        elif cmd in ("H", "h"):
            nx = num()
            if cmd == "h":
                nx += x
            x = nx
            poly.append((x, y))
        elif cmd in ("V", "v"):
            ny = num()
            if cmd == "v":
                ny += y
            y = ny
            poly.append((x, y))
        else:
            raise ValueError(f"unsupported SVG path command {cmd!r}")
    if poly:
        polys.append(poly)
    return polys


def _inside_evenodd(polys: list[list[tuple[float, float]]], px: float, py: float) -> bool:
    inside = False
    for poly in polys:
        n = len(poly)
        if n < 3:
            continue
        j = n - 1
        for i in range(n):
            xi, yi = poly[i]
            xj, yj = poly[j]
            if (yi > py) != (yj > py):
                xcross = (xj - xi) * (py - yi) / (yj - yi) + xi
                if px < xcross:
                    inside = not inside
            j = i
    return inside


def raster_svg(path: Path, out_w: int) -> tuple[int, int, bytes]:
    text = path.read_text()
    m = re.search(r'viewBox="([^"]+)"', text)
    if not m:
        raise ValueError("SVG has no viewBox")
    vx, vy, vw, vh = (float(v) for v in m.group(1).replace(",", " ").split())
    d = re.search(r'<path[^>]*\bd="([^"]+)"', text)
    if not d:
        raise ValueError("SVG has no path")
    polys = _svg_path_polygons(d.group(1))

    out_h = max(1, round(out_w * vh / vw))
    # 5x5 supersampling gives smooth edges without a float-heavy renderer.
    ss = 5
    mask = bytearray(out_w * out_h)
    for oy in range(out_h):
        for ox in range(out_w):
            hits = 0
            for sy in range(ss):
                py = vy + (oy + (sy + 0.5) / ss) * vh / out_h
                for sx in range(ss):
                    px = vx + (ox + (sx + 0.5) / ss) * vw / out_w
                    if _inside_evenodd(polys, px, py):
                        hits += 1
            mask[oy * out_w + ox] = (hits * 255 + ss * ss // 2) // (ss * ss)
    return out_w, out_h, bytes(mask)


def emit_header(logo: tuple[int, int, bytes]) -> str:
    lw, lh, ldata = logo

    def array(name: str, data: bytes, width: int = 16) -> str:
        lines = []
        for i in range(0, len(data), width):
            chunk = data[i:i + width]
            lines.append("    " + ", ".join(f"0x{b:02x}" for b in chunk) + ",")
        return f"static const unsigned char {name}[{len(data)}] = {{\n" + "\n".join(lines) + "\n};\n"

    return f"""/* Generated by tools/mkbootassets.py - do not edit by hand.
   Source: resources/axiome.svg. */
#ifndef AXIOME_BOOTSPLASH_ASSETS_H
#define AXIOME_BOOTSPLASH_ASSETS_H

#define SPLASH_LOGO_W {lw}
#define SPLASH_LOGO_H {lh}

/* 8-bit coverage mask, one byte per pixel, row-major. */
{array("splash_logo_mask", ldata)}
#endif /* AXIOME_BOOTSPLASH_ASSETS_H */
"""


def main() -> int:
    logo = raster_svg(RES / "axiome.svg", LOGO_W)
    OUT.write_text(emit_header(logo))
    print(f"wrote {OUT.relative_to(ROOT)} (logo {logo[0]}x{logo[1]})")
    return 0


if __name__ == "__main__":
    sys.exit(main())
